#include <stdio.h>
#include <stdint.h>

uint32_t six_middle_bits(uint32_t num) {
    // 13  6 13

    // 0b11010010101001010010111111111 &
    // 0b00000000000011111100000000000 =
    // 0b00000000000001010000000000000

    // 0b00000000000000000000000111111 << 13
    // 0b00000000000011111100000000000

    // 0b00000000000001010000000000000
    // 0b00000000000000000000000001010

    // 0b11010010101001010010111111111 > 13 =
    // 0b00000000000011010010101001010 &
    // 0b00000000000000000000001111111 =
    // 0b00000000000000000000000001010

    return (num >> 13) & 0b111111;
}   

int main(void) {
    printf("%08X\n", six_middle_bits(0xFFFFFFFF));

    // 0b00111111
    printf("%08X\n", six_middle_bits(0x00014000));
    // 0b00010100
    // 0b001010
}